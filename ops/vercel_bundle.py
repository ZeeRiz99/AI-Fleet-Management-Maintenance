"""Build the self-contained Vercel deployment folder for FleetLog AI (free Hobby plan, Python runtime).

    python -m ops.vercel_bundle                 build build/vercel (git-ignored)
    python -m ops.vercel_bundle --env-names     which environment variables Vercel needs (names only)
    python -m ops.vercel_bundle --push-env      copy those values from .env into the linked Vercel project
                                                (through the Vercel CLI's stdin: values are never printed)

Deploy (after `npx vercel@<CLI> login` once):
    cd build/vercel && npx vercel@<CLI> link --yes --project fleetlog-ai && npx vercel@<CLI> deploy --prod --yes

Verified Hobby limits (2026-10-22): functions 300 s max / 2 GB, 1M invocations and 4 h active CPU per month,
500 MB Python bundle, cron once per day with +-59 min precision (may fire twice: jobs must be idempotent),
non-commercial use only. Upstash Redis free: 500K commands/month, 256 MB.
"""
import json
import os
import shutil
import subprocess
import sys

from . import ROOT, env

CLI = "vercel@63.1.2"
OUT = ROOT / "build" / "vercel"
FILES = ["src/config.py", "src/db.py", "src/agent.py", "data/fleet.db", "data/processed/alerts.csv",
         "data/processed/fuel_anomalies.csv", "static-api/v1/fuel/baselines.json"]
REQUIRED = ["TELEGRAM_BOT_TOKEN", "TELEGRAM_WEBHOOK_SECRET", "UPSTASH_REDIS_REST_URL", "UPSTASH_REDIS_REST_TOKEN",
            "CRON_SECRET"]
OPTIONAL = ["GEMINI_API_KEY", "GROQ_API_KEY", "OPS_GEMINI_MODEL", "OPS_GROQ_MODEL", "OPS_GEMINI_STT_MODEL",
            "OPS_GROQ_STT_MODEL", "OPS_DEMO_MODE", "OPS_RESTRICT_MANAGER", "OPS_MAX_LLM_CALLS_PER_DAY",
            "OPS_MAX_MSGS_PER_USER_DAY", "OPS_MAX_MESSAGE_CHARS", "TELEGRAM_MANAGER_CHAT_IDS", "OPS_APP_KEY",
            "OPS_EVENTS_WEBHOOK_URL", "OPS_EVENTS_WEBHOOK_SECRET", "OPS_BRIEF_HOUR_PKT",
            "WHATSAPP_TOKEN", "WHATSAPP_PHONE_NUMBER_ID", "WHATSAPP_VERIFY_TOKEN", "WHATSAPP_APP_SECRET",
            "WHATSAPP_GRAPH_VERSION", "WHATSAPP_ALERT_TEMPLATE", "WHATSAPP_ALERT_TEMPLATE_LANG",
            "WHATSAPP_MANAGER_NUMBERS"]
LOCAL_ONLY = ["OPS_SQLITE_PATH", "OLLAMA_BASE_URL", "OPS_OLLAMA_MODEL", "OPS_LLM_PROVIDER"]

INDEX = '''"""Vercel entrypoint (generated by ops/vercel_bundle.py; edit that file, not this one)."""
import os
import shutil

if os.environ.get("VERCEL") and not os.environ.get("FLEET_DB_PATH"):
    # the deployment filesystem is read-only: read the demo fleet database from a /tmp copy
    if not os.path.exists("/tmp/fleet.db"):
        shutil.copyfile(os.path.join(os.path.dirname(__file__), "data", "fleet.db"), "/tmp/fleet.db")
    os.environ["FLEET_DB_PATH"] = "/tmp/fleet.db"

from ops.web import app  # noqa: E402,F401
'''


def brief_cron():
    """Vercel cron (UTC) for the morning brief: default 08:00 PKT = 03:00 UTC; Hobby fires within that hour."""
    hour_pkt = int(os.environ.get("OPS_BRIEF_HOUR_PKT", "8"))
    return {"path": "/cron/morning", "schedule": f"0 {(hour_pkt - 5) % 24} * * *"}


def requirements():
    lines = (ROOT / "requirements-ops.txt").read_text(encoding="utf-8").splitlines()
    return "\n".join(line for line in lines if line and not line.startswith(("#", "uvicorn"))) + "\n"


KEEP = (".vercel", ".env.local")  # the CLI's project link and its token survive rebuilds (never uploaded)


def build(out=OUT):
    keep = out.parent / ".vercel-keep"
    shutil.rmtree(keep, ignore_errors=True)
    for name in KEEP:
        if (out / name).exists():
            keep.mkdir(parents=True, exist_ok=True)
            shutil.move(str(out / name), str(keep / name))
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(ROOT / "ops", out / "ops", ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    for rel in FILES:
        (out / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, out / rel)
    (out / "index.py").write_text(INDEX, encoding="utf-8")
    (out / "requirements.txt").write_text(requirements(), encoding="utf-8")
    (out / ".python-version").write_text("3.14\n", encoding="utf-8")
    (out / "vercel.json").write_text(json.dumps({"$schema": "https://openapi.vercel.sh/vercel.json",
                                                 "crons": [brief_cron()]}, indent=2) + "\n", encoding="utf-8")
    # never upload local secrets: .env, and the .env.local the CLI writes on `vercel link`
    (out / ".vercelignore").write_text("__pycache__/\n*.pyc\n.env\n.env.*\n.vercel-keep/\n", encoding="utf-8")
    size = sum(f.stat().st_size for f in out.rglob("*") if f.is_file())
    for name in KEEP:
        if (keep / name).exists():
            shutil.move(str(keep / name), str(out / name))
    shutil.rmtree(keep, ignore_errors=True)
    return size


def push_env():
    """Copy the configured values from .env to the linked Vercel project (production). Values go through stdin."""
    env.load()
    if not (OUT / ".vercel").exists():
        sys.exit("Link the project first:  cd build/vercel && npx " + CLI + " link --yes --project fleetlog-ai")
    npx = shutil.which("npx") or "npx"
    done, missing = [], []
    for name in REQUIRED + OPTIONAL:
        value = os.environ.get(name, "")
        if not value:
            if name in REQUIRED:
                missing.append(name)
            continue
        subprocess.run([npx, "--yes", CLI, "env", "rm", name, "production", "--yes"], cwd=OUT,
                       capture_output=True)
        r = subprocess.run([npx, "--yes", CLI, "env", "add", name, "production"], cwd=OUT, input=value,
                           text=True, capture_output=True)
        (done if r.returncode == 0 else missing).append(name)
    print("Set on Vercel:", ", ".join(done) or "-")
    if missing:
        print("Missing or failed (set them in .env and re-run):", ", ".join(missing))


def main(argv):
    if "--env-names" in argv:
        print("Required:", ", ".join(REQUIRED))
        print("Optional:", ", ".join(OPTIONAL))
        print("Laptop only (not for Vercel):", ", ".join(LOCAL_ONLY))
    elif "--push-env" in argv:
        push_env()
    else:
        size = build()
        print(f"Built {OUT} ({size / 1e6:.1f} MB before dependencies). Deploy:\n"
              f"  cd {OUT}\n  npx {CLI} link --yes --project fleetlog-ai\n  npx {CLI} deploy --prod --yes")


if __name__ == "__main__":
    main(sys.argv[1:])
